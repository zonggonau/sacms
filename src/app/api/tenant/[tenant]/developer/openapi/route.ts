import { NextResponse } from "next/server"
import { db } from "@/lib/database"
import { withStaffAuth } from "@/lib/api/route-helpers"
import { EXCLUDE_PLATFORM_CONTENT_TYPES } from "@/lib/platform-content-types"

export const GET = withStaffAuth(async (_request, context, { access }) => {
    const { tenant: tenantSlug } = await context.params

    // 1. Fetch all tenant structures
    const [contentTypesRaw, singleTypesRaw] = await Promise.all([
      db.contentType.findMany({
        where: {
          // Exclude platform-internal types only among the *global*
          // (tenantId: null) rows — never hide a tenant's own content type
          // just because its slug happens to match a platform one.
          OR: [
            { tenantId: access.tenantId },
            { tenantId: null, ...EXCLUDE_PLATFORM_CONTENT_TYPES },
          ],
        },
        include: { schemaFields: true }
      }),
      db.singleType.findMany({
        where: { tenantId: access.tenantId },
        include: { schemaFields: true }
      })
    ])

    const contentTypes = contentTypesRaw.map(ct => ({ ...ct, fields: ct.schemaFields }))
    const singleTypes = singleTypesRaw.map(st => ({ ...st, fields: st.schemaFields }))

    const baseUrl = process.env.NEXTAUTH_URL || "http://localhost:3000"

    // 2. Build OpenAPI Object
    const spec: any = {
      openapi: "3.0.0",
      info: {
        title: `API Documentation - ${access.tenant.name}`,
        description: `Dynamic API documentation for ${access.tenant.name} workspace generated by SaCMS.`,
        version: "1.0.0",
      },
      servers: [
        {
          url: `${baseUrl}/api/public/${tenantSlug}`,
          description: "Public API Gateway"
        }
      ],
      components: {
        securitySchemes: {
          BearerAuth: {
            type: "http",
            scheme: "bearer",
            // Real tokens are opaque `cf_<64 hex chars>` strings generated by
            // generateToken() in src/actions/api-keys.ts — not JWTs. There is
            // nothing to decode/verify as a JWT; bearerFormat is left
            // unset rather than claiming a format the token doesn't follow.
            description: "Your workspace API Key, e.g. cf_xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx."
          }
        },
        schemas: {}
      },
      security: [{ BearerAuth: [] }],
      paths: {}
    }

    // Query parameters accepted by every collection GET — kept in sync by
    // hand with src/app/api/public/[tenant]/content/[contentType]/route.ts's
    // own searchParams.get(...) calls and src/lib/filters.ts. Filtering
    // itself (`filters[field][$op]=value`, e.g. filters[title][$eq]=Tutorial)
    // can't be enumerated as discrete OpenAPI parameters since the field and
    // operator are both caller-chosen — documented as free text instead;
    // the dashboard's own "Parameter & Filter Cheat Sheet" (REST Explorer
    // tab) has the full operator list.
    const collectionQueryParams = [
      { name: "page", in: "query", schema: { type: "integer", default: 1 }, description: "Page number (also accepted as pagination[page])." },
      { name: "pageSize", in: "query", schema: { type: "integer", default: 25, maximum: 100 }, description: "Entries per page, max 100 (also accepted as pagination[pageSize])." },
      { name: "sort", in: "query", schema: { type: "string", default: "createdAt:desc" }, description: "Field and direction, e.g. publishedAt:desc." },
      { name: "fields", in: "query", schema: { type: "string" }, description: "Comma-separated field slugs to return, e.g. title,slug." },
      { name: "populate", in: "query", schema: { type: "string" }, description: "Comma-separated relation field slugs to expand, or * for all." },
      { name: "locale", in: "query", schema: { type: "string" }, description: "Locale code to fetch, e.g. id or en." },
      { name: "status", in: "query", schema: { type: "string", enum: ["DRAFT", "PUBLISHED", "ARCHIVED"] }, description: "Filter by status — only honoured for full-access tokens; other callers always get PUBLISHED only." },
      { name: "search", in: "query", schema: { type: "string" }, description: "Full-text search across text fields." },
      { name: "filters", in: "query", schema: { type: "string" }, description: "Bracket-syntax field filters, e.g. filters[title][$eq]=Tutorial — see the REST Explorer's Parameter & Filter Cheat Sheet for the full operator list ($eq, $ne, $gt, $gte, $lt, $lte, $in, $notIn, $contains)." },
    ]

    // 3. Map Content Types to Paths & Schemas
    contentTypes.forEach(ct => {
      const schemaName = ct.slug.charAt(0).toUpperCase() + ct.slug.slice(1)

      const customFieldProps = ct.fields.reduce((acc: any, f) => {
        let type = "string"
        if (f.type === "number") type = "number"
        if (f.type === "boolean") type = "boolean"
        if (f.type === "json") type = "object"

        acc[f.slug] = {
          type,
          description: f.name,
          ...(f.required ? { nullable: false } : { nullable: true })
        }
        return acc
      }, {})

      // Entry schema: custom fields are spread FLAT alongside the base
      // fields (id/status/timestamps/...) — the real response never nests
      // them under a `data` sub-object. See the entry-shaping code at
      // src/app/api/public/[tenant]/content/[contentType]/route.ts (list)
      // and its [id]/route.ts (single entry).
      spec.components.schemas[schemaName] = {
        type: "object",
        properties: {
          id: { type: "string" },
          documentId: { type: "string" },
          locale: { type: "string" },
          availableLocales: { type: "array", items: { type: "string" } },
          status: { type: "string", enum: ["DRAFT", "PUBLISHED", "ARCHIVED"] },
          publishedAt: { type: "string", format: "date-time", nullable: true },
          createdAt: { type: "string", format: "date-time" },
          updatedAt: { type: "string", format: "date-time" },
          ...customFieldProps,
        }
      }

      // Input schema for create/update — only the caller-supplied custom
      // fields; id/status/timestamps are always server-generated.
      spec.components.schemas[`${schemaName}Input`] = {
        type: "object",
        properties: customFieldProps,
      }

      // Define Paths
      spec.paths[`/content/${ct.slug}`] = {
        get: {
          summary: `List all ${ct.name} entries`,
          tags: ["Collection Types"],
          parameters: collectionQueryParams,
          responses: {
            200: {
              description: "Paginated list of entries",
              content: {
                "application/json": {
                  schema: {
                    type: "object",
                    properties: {
                      data: { type: "array", items: { $ref: `#/components/schemas/${schemaName}` } },
                      meta: {
                        type: "object",
                        properties: {
                          contentType: { type: "object", properties: { name: { type: "string" }, slug: { type: "string" } } },
                          pagination: {
                            type: "object",
                            properties: {
                              page: { type: "integer" },
                              pageSize: { type: "integer" },
                              total: { type: "integer" },
                              totalPages: { type: "integer" },
                            }
                          }
                        }
                      }
                    }
                  }
                }
              }
            }
          }
        },
        post: {
          summary: `Create a new ${ct.name} (always created as DRAFT)`,
          tags: ["Collection Types"],
          requestBody: {
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    data: { $ref: `#/components/schemas/${schemaName}Input` },
                    locale: { type: "string", nullable: true }
                  },
                  required: ["data"]
                }
              }
            }
          },
          responses: {
            201: {
              description: "Created",
              content: {
                "application/json": {
                  schema: { type: "object", properties: { data: { $ref: `#/components/schemas/${schemaName}` } } }
                }
              }
            }
          }
        }
      }

      spec.paths[`/content/${ct.slug}/{id}`] = {
        get: {
          summary: `Get a specific ${ct.name} by ID or documentId`,
          tags: ["Collection Types"],
          parameters: [
            { name: "id", in: "path", required: true, schema: { type: "string" } },
            { name: "fields", in: "query", schema: { type: "string" } },
            { name: "populate", in: "query", schema: { type: "string" } },
            { name: "locale", in: "query", schema: { type: "string" } },
          ],
          responses: {
            200: {
              description: "Success",
              content: {
                "application/json": {
                  schema: { type: "object", properties: { data: { $ref: `#/components/schemas/${schemaName}` } } }
                }
              }
            }
          }
        },
        put: {
          summary: `Update a ${ct.name} entry (status is unchanged by this call)`,
          tags: ["Collection Types"],
          parameters: [{ name: "id", in: "path", required: true, schema: { type: "string" } }],
          requestBody: {
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: { data: { $ref: `#/components/schemas/${schemaName}Input` } },
                  required: ["data"]
                }
              }
            }
          },
          responses: {
            200: {
              description: "Updated",
              content: {
                "application/json": {
                  schema: { type: "object", properties: { data: { $ref: `#/components/schemas/${schemaName}` } } }
                }
              }
            }
          }
        },
        delete: {
          summary: `Delete a ${ct.name} entry`,
          tags: ["Collection Types"],
          parameters: [{ name: "id", in: "path", required: true, schema: { type: "string" } }],
          responses: {
            200: {
              description: "Deleted",
              content: {
                "application/json": {
                  schema: {
                    type: "object",
                    properties: { data: { type: "object", properties: { id: { type: "string" }, deleted: { type: "boolean" } } } }
                  }
                }
              }
            }
          }
        }
      }
    })

    // 4. Map Single Types
    singleTypes.forEach(st => {
      const schemaName = `${st.slug.charAt(0).toUpperCase() + st.slug.slice(1)}Single`
      const customFieldProps = st.fields.reduce((acc: any, f) => {
        let type = "string"
        if (f.type === "number") type = "number"
        if (f.type === "boolean") type = "boolean"
        if (f.type === "json") type = "object"
        acc[f.slug] = { type, description: f.name, ...(f.required ? { nullable: false } : { nullable: true }) }
        return acc
      }, {})

      spec.components.schemas[schemaName] = {
        type: "object",
        properties: {
          publishedAt: { type: "string", format: "date-time", nullable: true },
          updatedAt: { type: "string", format: "date-time" },
          ...customFieldProps,
        }
      }

      spec.paths[`/single/${st.slug}`] = {
        get: {
          summary: `Get ${st.name} data`,
          tags: ["Single Types"],
          parameters: [{ name: "locale", in: "query", schema: { type: "string" } }],
          responses: {
            200: {
              description: "Success",
              content: {
                "application/json": {
                  schema: { type: "object", properties: { data: { $ref: `#/components/schemas/${schemaName}` } } }
                }
              }
            }
          }
        },
        put: {
          summary: `Update ${st.name} data`,
          tags: ["Single Types"],
          parameters: [{ name: "locale", in: "query", schema: { type: "string" } }],
          requestBody: {
            content: {
              "application/json": {
                schema: {
                  type: "object",
                  properties: {
                    data: { type: "object", properties: customFieldProps },
                    publish: { type: "boolean", description: "Set publishedAt to now when true." }
                  },
                  required: ["data"]
                }
              }
            }
          },
          responses: {
            200: {
              description: "Updated",
              content: {
                "application/json": {
                  schema: { type: "object", properties: { data: { $ref: `#/components/schemas/${schemaName}` } } }
                }
              }
            }
          }
        }
      }
    })

    return NextResponse.json(spec)
})

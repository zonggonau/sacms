import { db, getTenantDb } from "@/lib/database"
import { materializeSchemaIntoTenant, type SchemaBlob } from "@/lib/schema-template-sync"
import { createContentEntry, type EntryWriteContext } from "@/lib/content/entry-service"

/**
 * Structural/reference field types with no sensible synthetic value (a real
 * media asset id, a real related record id, a real nested component shape,
 * an already-uploaded .docx) — same exclusion set Smart Fill's offline
 * fallback already uses (src/app/api/tenant/[tenant]/ai/smart-fill/route.ts),
 * plus `document_template` (needs a real uploaded file) and `slug` (always
 * auto-generated by processAutoSlugs from a sibling title field, never set
 * directly — see field-type-guide.ts).
 */
const SKIP_FIELD_TYPES = new Set([
  "media",
  "mediaMultiple",
  "file",
  "relation",
  "component",
  "repeater",
  "document_template",
  "slug",
])

interface SampleField {
  slug: string
  name: string
  type: string
  options?: Record<string, unknown> | null
}

/** Ground truth for each type's entry-value shape: src/lib/field-type-guide.ts */
function generateSampleFieldValue(field: SampleField, index: number): unknown | undefined {
  if (SKIP_FIELD_TYPES.has(field.type)) return undefined

  const label = field.name || field.slug
  const slugLower = field.slug.toLowerCase()
  if (["title", "judul", "nama", "name"].some((kw) => slugLower.includes(kw))) {
    return `Contoh ${label} ${index + 1}`
  }

  switch (field.type) {
    case "select": {
      const choices = (field.options as any)?.choices
      return Array.isArray(choices) && choices.length > 0 ? choices[0].value : undefined
    }
    case "multiselect": {
      const choices = (field.options as any)?.choices
      return Array.isArray(choices) && choices.length > 0 ? [choices[0].value] : []
    }
    case "tags":
      return ["contoh", "demo", "sacms"]
    case "seo":
      return {
        meta_title: `Contoh ${label}`,
        meta_description: "Deskripsi contoh untuk keperluan pratinjau demo Website Template.",
        keywords: ["sacms", "demo"],
        og_image: "",
        no_index: false,
      }
    case "rich-text":
    case "markdown":
    case "textarea":
    case "wysiwyg":
      return `Ini adalah konten contoh untuk ${label}, digunakan sebagai data demo pada pratinjau Website Template. Konten ini akan diganti dengan data asli saat pelanggan menerapkan template ke workspace mereka sendiri.`
    case "number":
    case "currency":
      return 100
    case "percent":
      return 80
    case "rating":
      return 5
    case "boolean":
      return true
    case "date":
    case "datetime":
      return new Date().toISOString().split("T")[0]
    case "dateRange": {
      const from = new Date()
      const to = new Date(from.getTime() + 7 * 86400000)
      return { from: from.toISOString().split("T")[0], to: to.toISOString().split("T")[0] }
    }
    case "location":
      return { lat: -6.2088, lng: 106.8456 }
    case "phone":
      return { code: "+62", number: "81234567890" }
    case "icon":
      return "Sparkles"
    case "code":
      return { code: "console.log('contoh')", language: "javascript" }
    case "button":
      return { text: "Pelajari Lebih Lanjut", url: "#", target: "_self" }
    case "email":
      return "demo@sacms.cloud"
    case "url":
      return "https://sacms.cloud"
    default:
      return `Contoh ${label} ${index + 1}`
  }
}

function buildSampleData(fields: SampleField[], index: number): Record<string, unknown> {
  const data: Record<string, unknown> = {}
  for (const field of fields) {
    const value = generateSampleFieldValue(field, index)
    if (value !== undefined) data[field.slug] = value
  }
  return data
}

async function reserveUniqueTenantSlug(preferred: string): Promise<string> {
  let candidate = preferred
  for (let attempt = 0; attempt < 5; attempt++) {
    const existing = await db.tenant.findUnique({ where: { slug: candidate } })
    if (!existing) return candidate
    candidate = `${preferred}-${Math.random().toString(36).slice(2, 6)}`
  }
  return candidate
}

const SAMPLE_ENTRIES_PER_CONTENT_TYPE = 3

/**
 * Lazily get-or-create the internal, owner-less demo tenant for a
 * SchemaTemplate — materializes its schema and seeds a few sample entries
 * the first time a demo deploy for ANY of its WebsiteTemplates runs.
 * Idempotent: a second/later call just returns the existing demo tenant.
 */
export async function ensureDemoTenantForSchemaTemplate(schemaTemplate: {
  id: string
  slug: string
  name: string
  schema: unknown
  demoTenantId: string | null
}): Promise<{ id: string; slug: string }> {
  if (schemaTemplate.demoTenantId) {
    const existing = await db.tenant.findUnique({
      where: { id: schemaTemplate.demoTenantId },
      select: { id: true, slug: true },
    })
    if (existing) return existing
  }

  const slug = await reserveUniqueTenantSlug(`demo-${schemaTemplate.slug}`)
  const tenant = await db.tenant.create({
    data: {
      name: `Demo: ${schemaTemplate.name}`,
      slug,
      plan: "enterprise",
      status: "active",
    },
    select: { id: true, slug: true },
  })

  const tenantDb = await getTenantDb(tenant.slug)
  await materializeSchemaIntoTenant(tenantDb, tenant.id, (schemaTemplate.schema as SchemaBlob) || {})

  await seedSampleContent(tenantDb, tenant.id, tenant.slug)

  await db.schemaTemplate.update({
    where: { id: schemaTemplate.id },
    data: { demoTenantId: tenant.id },
  })

  return tenant
}

async function seedSampleContent(tenantDb: Awaited<ReturnType<typeof getTenantDb>>, tenantId: string, tenantSlug: string) {
  const [contentTypes, singleTypes] = await Promise.all([
    tenantDb.contentType.findMany({ where: { tenantId }, include: { schemaFields: { orderBy: { order: "asc" } } } }),
    tenantDb.singleType.findMany({ where: { tenantId }, include: { schemaFields: { orderBy: { order: "asc" } } } }),
  ])

  const ctx: EntryWriteContext = { client: tenantDb, tenantId, tenantSlug }

  for (const contentType of contentTypes) {
    const fields = contentType.schemaFields.map((f) => ({ slug: f.slug, name: f.name, type: f.type, options: f.options as any }))
    for (let i = 0; i < SAMPLE_ENTRIES_PER_CONTENT_TYPE; i++) {
      await createContentEntry(ctx, { kind: "system" }, {
        contentTypeSlug: contentType.slug,
        data: buildSampleData(fields, i),
        status: "PUBLISHED",
      }).catch((err) => console.warn(`[demo-tenant] Failed to seed sample entry for ${contentType.slug}:`, err))
    }
  }

  for (const singleType of singleTypes) {
    const fields = singleType.schemaFields.map((f) => ({ slug: f.slug, name: f.name, type: f.type, options: f.options as any }))
    await tenantDb.tenantSingleTypeAssignment
      .create({
        data: {
          tenantId,
          singleTypeId: singleType.id,
          locale: "id",
          enabled: true,
          data: buildSampleData(fields, 0) as any,
          publishedAt: new Date(),
        },
      })
      .catch((err) => console.warn(`[demo-tenant] Failed to seed sample single-type data for ${singleType.slug}:`, err))
  }
}

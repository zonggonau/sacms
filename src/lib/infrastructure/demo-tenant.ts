/**
 * Structural/reference field types with no sensible synthetic value (a real
 * media asset id, a real related record id, a real nested component shape,
 * an already-uploaded .docx) — same exclusion set Smart Fill's offline
 * fallback already uses (src/app/api/tenant/[tenant]/ai/smart-fill/route.ts),
 * plus `document_template` (needs a real uploaded file) and `slug` (always
 * auto-generated by processAutoSlugs from a sibling title field, never set
 * directly — see field-type-guide.ts).
 */
const SKIP_FIELD_TYPES = new Set([
  "media",
  "mediaMultiple",
  "file",
  "relation",
  "component",
  "repeater",
  "document_template",
  "slug",
])

interface SampleField {
  slug: string
  name: string
  type: string
  options?: Record<string, unknown> | null
}

/** Ground truth for each type's entry-value shape: src/lib/field-type-guide.ts */
function generateSampleFieldValue(field: SampleField, index: number): unknown | undefined {
  if (SKIP_FIELD_TYPES.has(field.type)) return undefined

  const label = field.name || field.slug
  const slugLower = field.slug.toLowerCase()
  if (["title", "judul", "nama", "name"].some((kw) => slugLower.includes(kw))) {
    return `Contoh ${label} ${index + 1}`
  }

  switch (field.type) {
    case "select": {
      const choices = (field.options as any)?.choices
      return Array.isArray(choices) && choices.length > 0 ? choices[0].value : undefined
    }
    case "multiselect": {
      const choices = (field.options as any)?.choices
      return Array.isArray(choices) && choices.length > 0 ? [choices[0].value] : []
    }
    case "tags":
      return ["contoh", "demo", "sacms"]
    case "seo":
      return {
        meta_title: `Contoh ${label}`,
        meta_description: "Deskripsi contoh untuk keperluan pratinjau demo Website Template.",
        keywords: ["sacms", "demo"],
        og_image: "",
        no_index: false,
      }
    case "rich-text":
    case "markdown":
    case "textarea":
    case "wysiwyg":
      return `Ini adalah konten contoh untuk ${label}, digunakan sebagai data demo pada pratinjau Website Template. Konten ini akan diganti dengan data asli saat pelanggan menerapkan template ke workspace mereka sendiri.`
    case "number":
    case "currency":
      return 100
    case "percent":
      return 80
    case "rating":
      return 5
    case "boolean":
      // Third external audit, DEMO-4: this used to always return `true` —
      // for a flag like hideFromMenu/hideFromFooter that meant EVERY
      // seeded entry hid itself from navigation, making the whole demo's
      // menu/footer empty. Alternating gives a representative MIX
      // instead of a value that's uniformly wrong for roughly half of
      // all real-world boolean fields.
      return index % 2 === 0
    case "color":
      // DEMO-4: this type had no case at all, falling through to the
      // generic `Contoh ${label} ${index+1}` text default — not a color
      // at all, breaking anything that renders it as a swatch/CSS value.
      return "#2563eb"
    case "date":
    case "datetime":
      return new Date().toISOString().split("T")[0]
    case "dateRange": {
      const from = new Date()
      const to = new Date(from.getTime() + 7 * 86400000)
      return { from: from.toISOString().split("T")[0], to: to.toISOString().split("T")[0] }
    }
    case "location":
      return { lat: -6.2088, lng: 106.8456 }
    case "phone":
      return { code: "+62", number: "81234567890" }
    case "icon":
      return "Sparkles"
    case "code":
      return { code: "console.log('contoh')", language: "javascript" }
    case "button":
      return { text: "Pelajari Lebih Lanjut", url: "#", target: "_self" }
    case "email":
      return "demo@sacms.cloud"
    case "url":
      // DEMO-4: a plain "https://sacms.cloud" for EVERY url-type field —
      // including one plainly named e.g. coverUrl — looked obviously fake
      // and pointed at SaCMS's own marketing site, not a plausible image.
      // picsum.photos is a public placeholder-image service; seeded by
      // field slug + index so repeated entries don't all get one photo.
      return ["cover", "image", "photo", "thumbnail", "banner"].some((kw) => slugLower.includes(kw))
        ? `https://picsum.photos/seed/${encodeURIComponent(field.slug)}-${index}/800/450`
        : "https://example.com"
    default:
      return `Contoh ${label} ${index + 1}`
  }
}

function buildSampleData(fields: SampleField[], index: number): Record<string, unknown> {
  const data: Record<string, unknown> = {}
  for (const field of fields) {
    const value = generateSampleFieldValue(field, index)
    if (value !== undefined) data[field.slug] = value
  }
  return data
}

async function reserveUniqueTenantSlug(preferred: string, client: Pick<Prisma.TransactionClient, "tenant"> = db): Promise<string> {
  let candidate = preferred
  for (let attempt = 0; attempt < 5; attempt++) {
    const existing = await client.tenant.findUnique({ where: { slug: candidate } })
    if (!existing) return candidate
    candidate = `${preferred}-${Math.random().toString(36).slice(2, 6)}`
  }
  return candidate
}

const SAMPLE_ENTRIES_PER_CONTENT_TYPE = 3

/** Draft previews use the shared database and can be provisioned in the
 * same transaction that saves the catalog template. */
export async function createDraftDemoWorkspace(
  tx: Prisma.TransactionClient,
  template: { name: string; slug: string },
  schema: SchemaBlob,
) {
  const slug = await reserveUniqueTenantSlug(`demo-${template.slug}`, tx)
  const tenant = await tx.tenant.create({
    data: {
      name: `Demo: ${template.name}`,
      slug,
      plan: "enterprise",
      status: "active",
      locales: { create: { locale: "id", name: "Bahasa Indonesia", isDefault: true, isEnabled: true } },
    },
    select: { id: true, slug: true },
  })
  await materializeSchemaIntoTenant(tx, tenant.id, schema)
  return tenant
}

export async function findSchemaDemoWorkspace(
  client: Pick<Prisma.TransactionClient, "tenant">,
  template: { id: string; demoTenantId: string | null },
) {
  if (!template.demoTenantId) return null
  return client.tenant.findFirst({
    where: {
      id: template.demoTenantId,
      slug: { startsWith: "demo-" },
      ownerId: null,
      databaseUrl: null,
      status: "active",
      demoForSchemaTemplates: { some: { id: template.id }, every: { id: template.id } },
    },
    select: { id: true, slug: true },
  })
}

export async function syncDraftDemoWorkspace(
  tx: Prisma.TransactionClient,
  tenantId: string,
  previous: SchemaBlob,
  schema: SchemaBlob,
) {
  const nextSlugs = new Set(schema.contentTypes?.map((model) => model.slug))
  const removed = (previous.contentTypes || []).filter((model) => !nextSlugs.has(model.slug)).map((model) => model.slug)
  if (removed.length) {
    await tx.contentType.deleteMany({ where: { tenantId, draftTemplateId: null, slug: { in: removed } } })
  }

  const changed = (before: SchemaBlob["contentTypes"] = [], after: SchemaBlob["contentTypes"] = []) => {
    const bySlug = new Map(before.map((model) => [model.slug, model]))
    return after.filter((model) => !isDeepStrictEqual(bySlug.get(model.slug), model))
  }
  await materializeSchemaIntoTenant(tx, tenantId, {
    groups: schema.groups,
    contentTypes: isDeepStrictEqual(previous.groups, schema.groups)
      ? changed(previous.contentTypes, schema.contentTypes) : schema.contentTypes,
    singleTypes: changed(previous.singleTypes, schema.singleTypes),
    components: changed(previous.components, schema.components),
  }, {}, { updateExisting: true })
}

/**
 * Lazily get-or-create the internal, owner-less demo tenant for a
 * SchemaTemplate, then (re)materialize its schema and (re)seed sample
 * content — called on EVERY demo deploy (create, update with files/schema,
 * or an explicit redeploy), never just the first one.
 *
 * Fourth external audit, DEMO-6: this used to return the existing demo
 * tenant as-is once created — every LATER update/redeploy kept serving
 * whatever content got seeded the very first time, even after the
 * template's schema/dummyData genuinely changed (confirmed live: a
 * redeploy and an update with an identical-but-resaved schema both left
 * the demo tenant's content completely untouched). Every call that reaches
 * this function already means something schema/files-relevant changed —
 * update_website_template only triggers a redeploy when files or schema
 * actually changed (a metadata-only edit never calls deployWebsiteTemplateDemo
 * at all) — so a stale demo tenant is wiped (wipeTenantSchema — Content
 * Types/Single Types/Components, cascading their entries) and rebuilt from
 * scratch every time, not just once. This also makes
 * redeploy_website_template_demo double as a "force reseed" tool with no
 * new API surface needed.
 */
export async function ensureDemoTenantForSchemaTemplate(schemaTemplate: {
  id: string
  slug: string
  name: string
  schema: unknown
  demoTenantId: string | null
}): Promise<{ id: string; slug: string }> {
  if (schemaTemplate.demoTenantId) {
    const existing = await db.tenant.findUnique({
      where: { id: schemaTemplate.demoTenantId },
      select: { id: true, slug: true },
    })
    if (existing) {
      const tenantDb = await getTenantDb(existing.slug)
      const schemaBlob = (schemaTemplate.schema as SchemaBlob) || {}
      await wipeTenantSchema(tenantDb, existing.id)
      await materializeSchemaIntoTenant(tenantDb, existing.id, schemaBlob)
      await seedSampleContent(tenantDb, existing.id, existing.slug, schemaBlob)
      return existing
    }
  }

  const slug = await reserveUniqueTenantSlug(`demo-${schemaTemplate.slug}`)
  const tenant = await db.tenant.create({
    data: {
      name: `Demo: ${schemaTemplate.name}`,
      slug,
      plan: "enterprise",
      status: "active",
    },
    select: { id: true, slug: true },
  })

  // chatgpt.md P0: a brand-new tenant has no TenantLocale row at all — every
  // normal onboarding flow leaves that to a staff member, but this demo
  // tenant has none. createContentEntry's resolveWriteLocale falls back to
  // "en" when no TenantLocale is enabled for a tenant, while every public
  // read path (content list, single type) defaults to "id" when none is
  // configured — so seeded entries landed in a locale NOTHING ever reads
  // back, and the demo API reported 0 entries for every Content Type
  // (confirmed live). Seed the one default locale every other read/write
  // path already assumes.
  const tenantDb = await getTenantDb(tenant.slug)
  await tenantDb.tenantLocale.create({
    data: { tenantId: tenant.id, locale: "id", name: "Bahasa Indonesia", isDefault: true, isEnabled: true },
  })

  const schemaBlob = (schemaTemplate.schema as SchemaBlob) || {}
  await materializeSchemaIntoTenant(tenantDb, tenant.id, schemaBlob)

  await seedSampleContent(tenantDb, tenant.id, tenant.slug, schemaBlob)

  await db.schemaTemplate.update({
    where: { id: schemaTemplate.id },
    data: { demoTenantId: tenant.id },
  })

  return tenant
}

/**
 * A template author can supply real, hand-written `dummyData` rows per
 * Content Type/Single Type (see BundleModelRef in
 * schema-template-validation.ts — validated at create_schema_template/
 * create_website_template time via checkDummyData, against the SAME
 * per-field-type rules real content creation uses). Confirmed live
 * (the Kabar Nusa report): nothing downstream ever read it — the demo
 * tenant always got the fully generic `buildSampleData` output instead,
 * no matter how much real sample data a template author wrote. Looked up
 * by slug against the ORIGINAL schema blob (not the materialized tenant
 * rows, which have no column for it at all).
 */
function findDummyData(blobModels: { slug: string; [key: string]: unknown }[] | undefined, slug: string): Record<string, unknown>[] | undefined {
  const model = (blobModels || []).find((m) => m.slug === slug)
  const dummyData = model?.dummyData as unknown
  return Array.isArray(dummyData) && dummyData.length > 0 ? (dummyData as Record<string, unknown>[]) : undefined
}

/**
 * Builds one entry's data by starting from the generic synthesizer, then
 * overlaying whatever the author's own dummyData row actually provides —
 * so a field the author didn't bother filling (or couldn't, e.g. a
 * relation/media field dummyData's own validator doesn't support a
 * forward-reference for yet) still gets a non-empty placeholder instead of
 * silently reverting the whole entry to 100% generic data.
 */
function buildEntryData(fields: SampleField[], index: number, dummyRow: Record<string, unknown> | undefined): Record<string, unknown> {
  const generic = buildSampleData(fields, index)
  if (!dummyRow) return generic
  return { ...generic, ...dummyRow }
}

/** A stable, human-writable "natural key" for a seeded entry — derived from
 *  its own title/judul/name value, the same fields real content already
 *  treats as the identifying label (see generateSampleFieldValue's own
 *  title-like heuristic). Lets a relation dummyData value reference a
 *  target row by a plain slugified label (e.g. "nasional") instead of a
 *  real database id nobody writing a template bundle could ever know in
 *  advance. */
function computeNaturalKey(data: Record<string, unknown>): string | undefined {
  const raw = data.title ?? data.judul ?? data.nama ?? data.name
  if (typeof raw !== "string" || !raw.trim()) return undefined
  return slugify(raw)
}

interface PendingRelationPatch {
  contentTypeSlug: string
  entryId: string
  fieldSlug: string
  rawValue: unknown
  targetModelSlug: string
  isMulti: boolean
}

/**
 * Third external audit, DEMO-3: 'relation' dummyData values used to be
 * silently dropped entirely (SKIP_FIELD_TYPES) — every relation field in
 * the demo rendered empty no matter how explicit a template's own dummyData
 * was ("kategori": "nasional"). Resolved here as a plain slugified-label
 * reference against whichever OTHER Content Type's entries got seeded (by
 * computeNaturalKey, above) — not a new ref/_key format, just the author's
 * own dummyData string(s) matched by label. Runs as an explicit SECOND
 * pass, once every Content Type has already been seeded once, so a
 * self-relation or a circular pair (A -> B -> A) both resolve correctly:
 * by the time this runs, every entry that could ever be a valid target
 * already exists, regardless of model seeding order.
 *
 * Deliberately NOT handled: relation fields inside Single Types' own
 * dummyData (a single type has only one row, not a list to key-match
 * against in the same way), options.targetModel: "member" (no member
 * table exists in a template bundle to match against), and media/
 * component/repeater dummyData (no natural-key concept applies — flagged
 * separately, still out of scope for this round).
 */
async function resolveRelationPatches(
  ctx: EntryWriteContext,
  patches: PendingRelationPatch[],
  seededByModel: Map<string, Map<string, string>>,
) {
  for (const patch of patches) {
    const targetMap = seededByModel.get(patch.targetModelSlug)
    if (!targetMap) continue
    const resolveOne = (raw: unknown): string | undefined => (typeof raw === "string" ? targetMap.get(slugify(raw)) : undefined)

    // Coerce to the field's OWN declared shape regardless of how the
    // author happened to write dummyData (a single string for a *-to-many
    // field, or an array for a *-to-one) — rather than faithfully
    // reproducing a shape mismatch into real seeded content.
    let resolved: string | string[] | undefined
    if (patch.isMulti) {
      const rawArray = Array.isArray(patch.rawValue) ? patch.rawValue : [patch.rawValue]
      resolved = rawArray.map(resolveOne).filter((v): v is string => !!v)
    } else {
      const rawSingle = Array.isArray(patch.rawValue) ? patch.rawValue[0] : patch.rawValue
      resolved = resolveOne(rawSingle)
    }
    const hasValue = Array.isArray(resolved) ? resolved.length > 0 : !!resolved
    if (!hasValue) continue

    await updateContentEntry(ctx, { kind: "system" }, {
      contentTypeSlug: patch.contentTypeSlug,
      entryId: patch.entryId,
      data: { [patch.fieldSlug]: resolved },
    }).catch((err) => console.warn(`[demo-tenant] Failed to apply resolved relation for ${patch.contentTypeSlug}.${patch.fieldSlug}:`, err))
  }
}

async function seedSampleContent(tenantDb: Awaited<ReturnType<typeof getTenantDb>>, tenantId: string, tenantSlug: string, schemaBlob: SchemaBlob) {
  const [contentTypes, singleTypes] = await Promise.all([
    tenantDb.contentType.findMany({ where: { tenantId }, include: { schemaFields: { orderBy: { order: "asc" } } } }),
    tenantDb.singleType.findMany({ where: { tenantId }, include: { schemaFields: { orderBy: { order: "asc" } } } }),
  ])

  const ctx: EntryWriteContext = { client: tenantDb, tenantId, tenantSlug }

  // naturalKey -> real entry id, scoped per Content Type slug (a relation's
  // relationSlug always names a specific model — never "any").
  const seededByModel = new Map<string, Map<string, string>>()
  const pendingRelationPatches: PendingRelationPatch[] = []

  for (const contentType of contentTypes) {
    const fields = contentType.schemaFields.map((f) => ({ slug: f.slug, name: f.name, type: f.type, options: f.options as any, relationSlug: f.relationSlug }))
    const relationFields = fields.filter((f) => f.type === "relation" && f.relationSlug && (f.options as any)?.targetModel !== "member")
    const dummyRows = findDummyData(schemaBlob.contentTypes as any, contentType.slug)
    const entryCount = dummyRows ? Math.max(dummyRows.length, SAMPLE_ENTRIES_PER_CONTENT_TYPE) : SAMPLE_ENTRIES_PER_CONTENT_TYPE
    const keyMap = new Map<string, string>()
    seededByModel.set(contentType.slug, keyMap)

    for (let i = 0; i < entryCount; i++) {
      const dummyRow = dummyRows?.[i % dummyRows.length]
      const data = buildEntryData(fields, i, dummyRow)
      // A dummyData-provided relation value is a slugified LABEL reference
      // (resolved in the second pass below), never a real id — it must not
      // reach createContentEntry as-is, which would store the raw label
      // string as if it were an id.
      for (const rf of relationFields) delete data[rf.slug]

      const result = await createContentEntry(ctx, { kind: "system" }, {
        contentTypeSlug: contentType.slug,
        data,
        status: "PUBLISHED",
      }).catch((err): null => {
        console.warn(`[demo-tenant] Failed to seed sample entry for ${contentType.slug}:`, err)
        return null
      })
      if (!result || !result.ok) continue

      const naturalKey = computeNaturalKey(data)
      if (naturalKey) keyMap.set(naturalKey, result.data.id)

      if (dummyRow) {
        for (const rf of relationFields) {
          const rawValue = dummyRow[rf.slug]
          if (rawValue === undefined) continue
          const relationType = (rf.options as any)?.relationType
          pendingRelationPatches.push({
            contentTypeSlug: contentType.slug,
            entryId: result.data.id,
            fieldSlug: rf.slug,
            rawValue,
            targetModelSlug: rf.relationSlug!,
            isMulti: relationType === "oneToMany" || relationType === "manyToMany",
          })
        }
      }
    }
  }

  await resolveRelationPatches(ctx, pendingRelationPatches, seededByModel)

  for (const singleType of singleTypes) {
    const fields = singleType.schemaFields.map((f) => ({ slug: f.slug, name: f.name, type: f.type, options: f.options as any }))
    const singleDummyRows = findDummyData(schemaBlob.singleTypes as any, singleType.slug)
    // chatgpt.md P0: materializeSchemaIntoTenant's own `tenants: { create:
    // { tenantId } }` on each SingleType ALREADY inserts a
    // TenantSingleTypeAssignment row (empty data, publishedAt: null,
    // locale defaulting to "id") — the exact same [tenantId, singleTypeId,
    // locale] unique key this used to `.create()` again. That threw a
    // P2002 every time, silently swallowed by the catch below, so the real
    // sample data/publishedAt here never actually got applied and the
    // single type's demo API call 404'd as "not published" (confirmed
    // live). upsert instead of create, onto whichever row already exists.
    await tenantDb.tenantSingleTypeAssignment
      .upsert({
        where: { tenantId_singleTypeId_locale: { tenantId, singleTypeId: singleType.id, locale: "id" } },
        create: {
          tenantId,
          singleTypeId: singleType.id,
          locale: "id",
          enabled: true,
          data: buildEntryData(fields, 0, singleDummyRows?.[0]) as any,
          publishedAt: new Date(),
        },
        update: {
          enabled: true,
          data: buildEntryData(fields, 0, singleDummyRows?.[0]) as any,
          publishedAt: new Date(),
        },
      })
      .catch((err) => console.warn(`[demo-tenant] Failed to seed sample single-type data for ${singleType.slug}:`, err))
  }
}

import "server-only"

import type { UIMessage } from "ai"
import { nanoid } from "nanoid"
import { Prisma, type PrismaClient } from "../../../prisma/generated-client"

const TITLE_MAX_LENGTH = 80
export const MESSAGE_MAX_LENGTH = 20_000

export type ChatSummary = { id: string; title: string; updatedAt: string }

export async function listChats(tenantDb: PrismaClient, projectId: string): Promise<ChatSummary[]> {
  const rows = await tenantDb.aiSiteChat.findMany({
    where: { projectId },
    select: { id: true, title: true, updatedAt: true },
    orderBy: { updatedAt: "desc" },
    take: 100,
  })

  return rows.map((row) => ({ ...row, updatedAt: row.updatedAt.toISOString() }))
}

/** A chat with its project, when both belong to this tenant. */
export async function getTenantChat(tenantDb: PrismaClient, chatId: string) {
  return tenantDb.aiSiteChat.findUnique({
    where: { id: chatId },
    include: { project: true },
  })
}

/** Creates a chat whose first message is `text`; the reply is generated by the chat page. */
export async function createChat(
  tenantDb: PrismaClient,
  projectId: string,
  userId: string | null,
  text: string,
  model?: string | null,
) {
  const chat = await tenantDb.aiSiteChat.create({
    data: { projectId, createdByUserId: userId, title: titleFrom(text), model: model || null },
  })

  await saveMessages(tenantDb, chat.id, [userMessage(text)])
  return chat
}

export function userMessage(text: string): UIMessage {
  return { id: nanoid(16), role: "user", parts: [{ type: "text", text }] }
}

export async function loadMessages(tenantDb: PrismaClient, chatId: string): Promise<UIMessage[]> {
  const rows = await tenantDb.aiSiteChatMessage.findMany({
    where: { chatId },
    orderBy: [{ createdAt: "asc" }, { id: "asc" }],
  })

  return rows.map((row) => ({
    id: row.id,
    role: row.role as UIMessage["role"],
    parts: row.parts as UIMessage["parts"],
    ...(row.metadata ? { metadata: row.metadata } : {}),
  }))
}

/** Inserts new messages and updates existing ones (matched by id) in order. */
export async function saveMessages(tenantDb: PrismaClient, chatId: string, messages: UIMessage[]) {
  if (messages.length === 0) return

  // Messages saved together keep their order through strictly increasing timestamps.
  // Sequential, not a batched $transaction([...]) — dedicated-tenant clients
  // are wrapped in a connection-fallback Proxy (database.ts) whose .catch()
  // wrapping strips the PrismaPromise branding $transaction's array form
  // requires, so a batch call throws "All elements of the array need to be
  // Prisma Client promises."
  const start = Date.now()
  for (const [index, message] of messages.entries()) {
    await tenantDb.aiSiteChatMessage.upsert({
      where: { id: message.id },
      create: {
        id: message.id,
        chatId,
        role: message.role,
        parts: message.parts as object,
        metadata: (message.metadata as object | undefined) ?? Prisma.JsonNull,
        createdAt: new Date(start + index),
      },
      update: {
        parts: message.parts as object,
        metadata: (message.metadata as object | undefined) ?? Prisma.JsonNull,
      },
    })
  }
  await tenantDb.aiSiteChat.update({ where: { id: chatId }, data: { updatedAt: new Date() } })
}

export async function deleteMessages(tenantDb: PrismaClient, chatId: string, messageIds: string[]) {
  if (messageIds.length === 0) return
  await tenantDb.aiSiteChatMessage.deleteMany({
    where: { chatId, id: { in: messageIds } },
  })
}

export async function renameChat(tenantDb: PrismaClient, chatId: string, title: string) {
  await tenantDb.aiSiteChat.update({ where: { id: chatId }, data: { title: titleFrom(title) } })
}

export async function deleteChat(tenantDb: PrismaClient, chatId: string) {
  await tenantDb.aiSiteChat.delete({ where: { id: chatId } })
}

function titleFrom(text: string) {
  const line = text.trim().split("\n")[0]!.trim()
  return line.length > TITLE_MAX_LENGTH ? `${line.slice(0, TITLE_MAX_LENGTH - 1)}…` : line || "Untitled"
}

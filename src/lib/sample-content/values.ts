/**
 * Sample values per field type, shaped the way the content API stores them
 * (see field-type-guide.ts entryValue). Deterministic: the same index always
 * gives the same value, so a re-run produces the same data.
 */
import type { SampleField, SampleModel, SampleSchema } from "./plan"

export interface ValueContext {
  /** 0-based entry index within the Content Type. */
  index: number
  contentTypeName: string
  /** Real entry ids already written for a relation target slug (or reused from the workspace). */
  relationIds: (targetSlug: string) => string[]
  schema: SampleSchema
}

const TITLE_LIKE = new Set(["title", "judul", "name", "nama"])
const COLORS = ["#0f766e", "#b45309", "#1d4ed8", "#be123c", "#4d7c0f"]
const ICONS = ["Star", "Heart", "Home", "Coffee", "Leaf"]
// Nabire, Papua Tengah: the project's home region, so location samples look real.
const NABIRE = { lat: -3.3667, lng: 135.4833 }

function label(field: SampleField, ctx: ValueContext): string {
  const n = ctx.index + 1
  return TITLE_LIKE.has(field.slug) ? `Contoh ${ctx.contentTypeName} ${n}` : `${field.name} ${n}`
}

function choiceValues(field: SampleField): string[] {
  const choices = field.options?.choices
  return Array.isArray(choices) ? choices.map((c: any) => String(c.value)).filter(Boolean) : []
}

function pad(n: number): string {
  return String(n).padStart(2, "0")
}

/** Value for one field, or `undefined` when the field should be left unset. */
export function sampleFieldValue(field: SampleField, ctx: ValueContext, depth = 0): unknown {
  const n = ctx.index + 1
  switch (field.type) {
    case "slug":
      return undefined // generated by the system from the title field
    case "text":
    case "textarea":
      return label(field, ctx)
    case "email":
      return `contoh${n}@example.com`
    case "url":
      return `https://example.com/contoh-${n}`
    case "richText":
      return `<p>Contoh konten ${n} untuk ${ctx.contentTypeName}.</p>`
    case "markdown":
      return `**Contoh** konten ${n} untuk ${ctx.contentTypeName}.`
    case "number":
      return n
    case "currency":
      return 15000 + ctx.index * 5000
    case "percent":
      return Math.min(100, 10 * n)
    case "rating":
      return (ctx.index % 5) + 1
    case "boolean":
      return ctx.index % 2 === 0
    case "date":
      return `2026-01-${pad(n)}`
    case "datetime":
      return `2026-01-${pad(n)}T09:00:00.000Z`
    case "time":
      return `${pad(8 + (ctx.index % 10))}:00`
    case "dateRange":
      return { from: `2026-01-${pad(n)}`, to: `2026-01-${pad(n + 1)}` }
    case "select": {
      const values = choiceValues(field)
      return values.length ? values[ctx.index % values.length] : undefined
    }
    case "multiselect": {
      const values = choiceValues(field)
      return values.length ? [values[ctx.index % values.length]] : undefined
    }
    case "tags":
      return [`contoh-${n}`, "sample"]
    case "color":
      return COLORS[ctx.index % COLORS.length]
    case "icon":
      return ICONS[ctx.index % ICONS.length]
    case "phone":
      return { code: "+62", number: `81200000${String(10 + ctx.index)}` }
    case "location":
      return { lat: NABIRE.lat, lng: NABIRE.lng }
    case "seo":
      return {
        meta_title: `${label(field, ctx)} | Contoh`,
        meta_description: `Deskripsi contoh untuk ${ctx.contentTypeName} nomor ${n}.`,
        keywords: "contoh, sample",
        no_index: false,
      }
    case "code":
      return { code: `console.log("contoh ${n}");`, language: "javascript" }
    case "button":
      return { text: "Lihat selengkapnya", url: "/" }
    case "json":
      return {}
    case "relation": {
      const ids = ctx.relationIds(field.relationSlug ?? "")
      if (ids.length === 0) return undefined
      const many = field.options?.relationType === "oneToMany" || field.options?.relationType === "manyToMany"
      return many ? [ids[ctx.index % ids.length]] : ids[ctx.index % ids.length]
    }
    case "component": {
      const compSlug = field.options?.componentSlug ?? (field as any).componentSlug
      const comp = ctx.schema.components.find((c) => c.slug === compSlug)
      if (!comp || depth > 1) return undefined
      const value = componentValue(comp, ctx, depth + 1)
      return field.options?.repeatable ? [value] : value
    }
    case "repeater": {
      const allowed: string[] = Array.isArray(field.options?.allowedComponents) ? field.options!.allowedComponents : []
      const comp = ctx.schema.components.find((c) => allowed.includes(c.slug))
      if (!comp || depth > 1) return undefined
      return [{ __component: comp.slug, ...componentValue(comp, ctx, depth + 1) }]
    }
    default:
      return undefined
  }
}

function componentValue(comp: SampleModel, ctx: ValueContext, depth: number): Record<string, unknown> {
  const out: Record<string, unknown> = {}
  for (const f of comp.fields) {
    const v = sampleFieldValue(f, { ...ctx, contentTypeName: comp.name }, depth)
    if (v !== undefined) out[f.slug] = v
  }
  return out
}

/** Full data object for one entry. Undefined values are left out, never sent as null. */
export function sampleEntryData(ct: SampleModel, fields: string[], ctx: ValueContext): Record<string, unknown> {
  const data: Record<string, unknown> = {}
  for (const slug of fields) {
    const field = ct.fields.find((f) => f.slug === slug)
    if (!field) continue
    const v = sampleFieldValue(field, { ...ctx, contentTypeName: ct.name })
    if (v !== undefined) data[slug] = v
  }
  return data
}

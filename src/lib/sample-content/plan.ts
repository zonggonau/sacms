/**
 * Sample-content planner. Pure: reads a schema and says what could be seeded,
 * in what order, and what could not be filled automatically. Nothing is
 * written here; the runner in run.ts does that from this plan.
 *
 * Scope (v1): Content Types only. Single Types and Components are not seeded
 * as entries (a Component is filled inside the entry that uses it).
 */
import { createHash } from "crypto"

export interface SampleField {
  name: string
  slug: string
  type: string
  required?: boolean
  options?: Record<string, any> | null
  relationSlug?: string | null
}

export interface SampleModel {
  name: string
  slug: string
  fields: SampleField[]
}

export interface SampleSchema {
  contentTypes: SampleModel[]
  singleTypes?: SampleModel[]
  components: SampleModel[]
}

export interface PlanOptions {
  locale: string
  /** Entries per Content Type. Clamped to 1..MAX_PER_TYPE. */
  perType?: number
  /** Content Type slugs to consider. Omit for all. */
  contentTypes?: string[]
  /** Current entry count per Content Type slug in this workspace or demo. */
  existingCounts?: Record<string, number>
}

export const MAX_PER_TYPE = 10
export const DEFAULT_PER_TYPE = 3
export const SEED_VERSION = "1"

export interface PlanStep {
  contentType: string
  count: number
  /** Content Types this one's relation fields point at, which must be written first. */
  dependsOn: string[]
  /** Fields that will be filled, in schema order. */
  fields: string[]
}

export interface PlanIssue {
  contentType: string
  field?: string
  reason: string
}

export interface SamplePlan {
  locale: string
  perType: number
  batchKey: string
  steps: PlanStep[]
  /** Content Types left out entirely, with the reason. */
  skipped: PlanIssue[]
  /** Optional fields that cannot be filled automatically; the entry is still written without them. */
  unfillable: PlanIssue[]
}

const TITLE_LIKE = new Set(["title", "judul", "name", "nama"])
const MEDIA_TYPES = new Set(["media", "mediaMultiple", "file", "document_template"])
const MEMBER_TARGET = "member"

function clampPerType(n: number | undefined): number {
  if (!n || !Number.isFinite(n)) return DEFAULT_PER_TYPE
  return Math.min(MAX_PER_TYPE, Math.max(1, Math.floor(n)))
}

export function batchKeyFor(schema: SampleSchema, locale: string, perType: number, contentTypes: string[]): string {
  const material = JSON.stringify({
    v: SEED_VERSION,
    locale,
    perType,
    contentTypes: [...contentTypes].sort(),
    shape: schema.contentTypes.map((ct) => [ct.slug, ct.fields.map((f) => [f.slug, f.type, f.relationSlug ?? null])]),
  })
  return createHash("sha256").update(material).digest("hex").slice(0, 16)
}

/** Relation target of a field, or null when it is not a Content Type relation. */
function relationTarget(field: SampleField): string | null {
  if (field.type !== "relation") return null
  if (field.options?.targetModel === MEMBER_TARGET) return null
  return field.relationSlug ?? null
}

interface FieldVerdict {
  fillable: boolean
  dependsOn?: string
  reason?: string
  required: boolean
}

function judgeField(field: SampleField, schema: SampleSchema, ctSlugs: Set<string>, existingCounts: Record<string, number>): FieldVerdict {
  const required = !!field.required
  const no = (reason: string): FieldVerdict => ({ fillable: false, reason, required })

  if (field.type === "slug") {
    // Auto-generated by the system from a sibling title field; never set here.
    return { fillable: true, required, reason: undefined }
  }
  if (field.type === "relation") {
    if (field.options?.targetModel === MEMBER_TARGET) {
      return no("relasi ke Member butuh akun member yang sudah ada; isi manual")
    }
    const target = field.relationSlug
    if (!target) return no("relasi belum menunjuk Content Type tujuan")
    if (ctSlugs.has(target)) return { fillable: true, dependsOn: target, required }
    if ((existingCounts[target] ?? 0) > 0) return { fillable: true, required }
    return no(`Content Type tujuan "${target}" tidak ada atau kosong`)
  }
  if (field.type === "component") {
    const comp = field.options?.componentSlug ?? (field as any).componentSlug
    if (!comp) return no("komponen belum dipilih")
    if (!schema.components.some((c) => c.slug === comp)) return no(`komponen "${comp}" tidak ditemukan`)
    return { fillable: true, required }
  }
  if (field.type === "repeater") {
    const allowed: string[] = Array.isArray(field.options?.allowedComponents) ? field.options!.allowedComponents : []
    const usable = allowed.filter((s) => schema.components.some((c) => c.slug === s))
    if (usable.length === 0) return no("repeater tanpa komponen yang diizinkan")
    return { fillable: true, required }
  }
  if (MEDIA_TYPES.has(field.type)) {
    return no("butuh file atau media yang diunggah; belum bisa dibuat otomatis")
  }
  if (field.type === "password" || field.type === "uid") {
    return no(`tipe ${field.type} tidak diisi otomatis`)
  }
  return { fillable: true, required }
}

/**
 * Builds the plan. A Content Type is skipped when a required field cannot be
 * filled, when a relation it needs is unavailable, when it already has
 * entries, or when it is part of a relation cycle. Optional unfillable fields
 * are reported and the entry is written without them.
 */
export function buildSamplePlan(schema: SampleSchema, options: PlanOptions): SamplePlan {
  const locale = options.locale
  const perType = clampPerType(options.perType)
  const existingCounts = options.existingCounts ?? {}
  const wanted = options.contentTypes ? new Set(options.contentTypes) : null
  const skipped: PlanIssue[] = []
  const unfillable: PlanIssue[] = []

  const candidates: SampleModel[] = []
  for (const ct of schema.contentTypes) {
    if (wanted && !wanted.has(ct.slug)) continue
    if ((existingCounts[ct.slug] ?? 0) > 0) {
      skipped.push({ contentType: ct.slug, reason: `sudah berisi ${existingCounts[ct.slug]} entri; tidak ditimpa` })
      continue
    }
    candidates.push(ct)
  }

  // First pass: per Content Type, which fields fill and what it depends on.
  const verdicts = new Map<string, { fields: string[]; deps: Set<string>; blocked?: string }>()
  const candidateSlugs = new Set(candidates.map((c) => c.slug))
  for (const ct of candidates) {
    const fields: string[] = []
    const deps = new Set<string>()
    let blocked: string | undefined
    for (const field of ct.fields) {
      const v = judgeField(field, schema, candidateSlugs, existingCounts)
      if (!v.fillable) {
        if (v.required) {
          blocked = blocked ?? `field wajib "${field.slug}" ${v.reason}`
        } else {
          unfillable.push({ contentType: ct.slug, field: field.slug, reason: v.reason! })
        }
        continue
      }
      if (field.type === "slug" && !ct.fields.some((f) => TITLE_LIKE.has(f.slug))) {
        unfillable.push({ contentType: ct.slug, field: field.slug, reason: "slug dibuat dari field judul, tapi tidak ada field title/judul/name/nama" })
        continue
      }
      fields.push(field.slug)
      if (v.dependsOn) deps.add(v.dependsOn)
    }
    verdicts.set(ct.slug, { fields, deps, blocked })
  }

  // Drop blocked Content Types, and anything that depends on one, until stable.
  let changed = true
  while (changed) {
    changed = false
    for (const ct of candidates) {
      const v = verdicts.get(ct.slug)
      if (!v || v.blocked) continue
      for (const dep of v.deps) {
        const depVerdict = verdicts.get(dep)
        if (depVerdict?.blocked) {
          v.blocked = `relasi ke "${dep}" yang dilewati`
          changed = true
          break
        }
        // A dependency that is neither planned nor already populated cannot be satisfied.
        if (!depVerdict && !((existingCounts[dep] ?? 0) > 0)) {
          v.blocked = `relasi ke "${dep}" tidak tersedia`
          changed = true
          break
        }
      }
    }
  }

  // Topological order over the survivors. A cycle leaves Content Types behind.
  const alive = candidates.filter((ct) => !verdicts.get(ct.slug)!.blocked)
  const order: string[] = []
  const placed = new Set<string>()
  let progress = true
  while (progress) {
    progress = false
    for (const ct of alive) {
      if (placed.has(ct.slug)) continue
      const deps = [...verdicts.get(ct.slug)!.deps].filter((d) => verdicts.has(d))
      if (deps.every((d) => placed.has(d))) {
        order.push(ct.slug)
        placed.add(ct.slug)
        progress = true
      }
    }
  }
  for (const ct of alive) {
    if (!placed.has(ct.slug)) skipped.push({ contentType: ct.slug, reason: "relasi melingkar antar Content Type" })
  }
  for (const ct of candidates) {
    const v = verdicts.get(ct.slug)!
    if (v.blocked) skipped.push({ contentType: ct.slug, reason: v.blocked })
  }

  const steps: PlanStep[] = order.map((slug) => {
    const v = verdicts.get(slug)!
    return {
      contentType: slug,
      count: perType,
      dependsOn: [...v.deps].filter((d) => verdicts.has(d)),
      fields: v.fields,
    }
  })

  return {
    locale,
    perType,
    batchKey: batchKeyFor(schema, locale, perType, [...(wanted ?? schema.contentTypes.map((ct) => ct.slug))]),
    steps,
    skipped,
    unfillable,
  }
}
